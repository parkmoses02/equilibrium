// node export-fw.js [--check] : emit or verify the immutable 5 ms firmware trajectory.
const {sim,makeTracker,dt,stride,N}=require('./model');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
// Re-fit the first 12 velocity knots by shooting with the 13th fixed to zero.
const knots=[-.3556646759,-.7817771703,-.7085725013,-.3828593949,.1837889579,-.0823366770,.4664177010,.4807140700,.1073784552,.1148660775,.6033202195,.3552352979,0];
const tracker=makeTracker(knots);
// Leave the final 120 ms at zero nominal speed; feedback remains active.
assert(tracker.frames.slice(N*stride,(N+1)*stride+1).every(f=>Math.abs(f[4])<1e-6),'missing terminal braking interval');
assert(dt===.005 && tracker.gains.length===(N+1)*stride);
for(const variant of ['nominal','offset','delay']){
 const z=sim(knots,true,4,variant,tracker);assert(z.held && z.maxX<.28 && z.maxA<=16.00001 && z.maxV<=.800001);
}
const rows=tracker.gains.map((gain,i)=>{
 const [,x,a,b,v]=tracker.frames[i],u=tracker.frames[i+1][7];
 return '    {'+[x,a,b,v,u,...gain].map(x=>x.toFixed(8)+'f').join(',')+'},';
});
const out='// Generated by simulation/dd-du/export-fw.js. SI units; absolute angles from up.\n#pragma once\nstruct DuFrame {float x,base,tip,v,u,k[6];};\nstatic constexpr DuFrame duFrames[]={\n'+rows.join('\n')+'\n};\n';
const dest=path.join(__dirname,'../../src/double_pendulum/du_frames.h');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(dest,'utf8').replace(/\r\n/g,'\n'),out);
else fs.writeFileSync(dest,out);
